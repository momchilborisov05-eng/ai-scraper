RATING_WORDS = ["Zero", "One", "Two", "Three", "Four", "Five"]


def stable(text: str) -> int:
    return zlib.crc32(text.encode())


def name() -> str:
    return f"{R.choice(FIRST)} {R.choice(LAST)}"


def title() -> str:
    return f"The {R.choice(ADJ)} {R.choice(NOUN)}"


def page(site: str, body: str, title_text: str, sidebar: bool = True) -> str:
    nav = "".join(f'<li><a href="/{w.lower()}/">{w}</a></li>' for w in ("Home", "Browse", "Deals", "About", "Help"))
    side = ""
    if sidebar:
        cats = ["Travel", "Mystery", "History", "Poetry", "Science", "Romance", "Fantasy", "Horror", "Humor",
                "Business", "Music", "Sports", "Health", "Art", "Food", "Philosophy"]
        side = ('<div class="side-col"><h3>Categories</h3><ul class="categories">' +
                "".join(f'<li><a href="/category/{c.lower()}/">{c}</a></li>' for c in cats) + "</ul></div>")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{escape(title_text)} | {site}</title>
<style>body{{font-family:sans-serif}} .hidden{{display:none}}</style>
<script>window.analytics = {{track: function(){{}}}};</script></head>
<body>
<header class="site-header"><a class="logo" href="/">{site}</a><nav><ul>{nav}</ul></nav>
<form class="search" action="/search"><input name="q" placeholder="Search"><button>Go</button></form></header>
<div class="layout">{side}
<main class="content"><h1>{escape(title_text)}</h1>
{body}
</main></div>
<footer class="site-footer"><p>&copy; 2026 {site}. All rights reserved.</p>
<ul><li><a href="/privacy">Privacy</a></li><li><a href="/terms">Terms</a></li><li><a href="/contact">Contact</a></li></ul>
</footer>
<div class="cookie-banner">We use cookies. <a href="/cookies">Learn more</a></div>
</body></html>
"""


def write(name_: str, request: str, notes: str, base: str, fields: list[tuple[str, str, str]],
          pages: list[str], records: list[dict]) -> None:
    d = OUT / name_
    d.mkdir(parents=True, exist_ok=True)
    for old in d.glob("*.html"):
        old.unlink()
    page_specs = []
    for i, html in enumerate(pages, 1):
        fname = f"page{i}.html"
        (d / fname).write_text(html, encoding="utf-8", newline="\n")
        page_specs.append({"url": base.format(i), "file": fname})
    spec = {"request": request, "notes": notes,
            "schema": {"description": request, "base_url": "",
                       "fields": [{"name": n, "type": t, "description": desc} for n, t, desc in fields]},
            "pages": page_specs}
    (d / "spec.json").write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
                                 newline="\n")
    (d / "gold.json").write_text(json.dumps(records, indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                                 newline="\n")


