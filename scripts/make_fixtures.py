"""Generate the evaluation fixtures: saved listing pages + hand-checkable ground truth.

Deterministic (fixed seed), so the files in fixtures/ can be regenerated byte for byte. Each fixture mimics a real
layout family and carries the noise real pages have: a header nav, a decoy sidebar list of links, a footer,
interleaved ads, missing values, values hidden in attributes, several values in one text node, multi-row records
and pagination. The ground truth is written from the same data the page was rendered from, so it is exact.

    python scripts/make_fixtures.py
"""

from __future__ import annotations

